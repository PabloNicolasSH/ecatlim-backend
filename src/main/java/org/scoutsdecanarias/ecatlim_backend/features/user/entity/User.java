package org.scoutsdecanarias.ecatlim_backend.features.user.entity;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.scoutsdecanarias.ecatlim_backend.features.education_stage.EducationStage;
import org.scoutsdecanarias.ecatlim_backend.features.education_stage.UserEducationStage;
import org.scoutsdecanarias.ecatlim_backend.features.lesson_block.UserLessonBlock;
import org.scoutsdecanarias.ecatlim_backend.features.user.enums.Role;

import java.time.LocalDateTime;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

@Getter
@Setter
@Entity
public class User {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    @Column(nullable = false, unique = true)
    private String email;

    @JsonIgnore
    @Column(nullable = false)
    private String password;

    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(
            name = "user_roles",
            joinColumns = @JoinColumn(name = "user_id")
    )
    @Enumerated(EnumType.STRING)
    @Column(name = "role", nullable = false)
    private Set<Role> roles = new HashSet<>();

    private boolean enabled = true;

    private boolean emailRemindersEnabled = true;

    private boolean onboardingCompleted = false;

    /** The password was generated by the system or reset by an admin, so it must be changed before anything else. */
    private boolean mustChangePassword = false;

    private LocalDateTime passwordChangedAt;

    /** Encrypted TOTP secret. Only usable for logins once totpEnabled is set by confirming a first code. */
    @JsonIgnore
    private String totpSecret;

    private boolean totpEnabled = false;

    /** Time step of the last accepted TOTP code, so a code cannot be replayed. */
    @JsonIgnore
    private Long totpLastStep;

    @ManyToOne
    @JoinColumn(name = "trainer_stage_id")
    private EducationStage trainerStage;

    @OneToOne(mappedBy = "user", cascade = CascadeType.ALL)
    private UserProfile profile;

    @OneToMany(mappedBy = "user", cascade = CascadeType.ALL)
    private List<UserLessonBlock> lessonBlocks;

    @OneToMany(mappedBy = "user", cascade = CascadeType.ALL)
    private List<UserEducationStage> educationStages;
}
